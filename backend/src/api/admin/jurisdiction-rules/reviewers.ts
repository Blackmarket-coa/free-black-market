import type { MedusaRequest } from "@medusajs/framework/http"
import { Modules } from "@medusajs/framework/utils"

/**
 * Who may sign off a jurisdiction rule.
 *
 * A sign-off is the one step in the rule store that turns a draft into text
 * shown as reviewed, so it is not open to every admin. The operator names the
 * reviewers in the environment, by admin **user id**:
 *
 *   JURISDICTION_RULE_REVIEWER_USER_IDS=user_01HX...,user_01HY...
 *
 * **Unset or empty means nobody can review.** There is no default reviewer and
 * no fallback to "any admin": a deployment that forgot the variable must fail
 * closed, not open.
 *
 * Why user ids and not emails. An email is not a login's identity in Medusa:
 * any admin can delete another admin user, the delete is a soft delete, and
 * the unique index on `user.email` covers only live rows, so the deleted
 * owner's address can be registered again by anyone who can send and accept
 * an invite. Matched by email, that impostor passed as the reviewer and the
 * real owner was refused (measured in the PL-2 review). A user id is
 * generated by Medusa, never reused, and a deleted user cannot be retrieved,
 * so a deleted reviewer's id admits nobody, and a new user with the same email
 * gets a different id. The operator's step stays the owner's decision as
 * recorded (SD-154: "the operator adds the owner's admin login"); the user id
 * names that login exactly. `JURISDICTION_RULE_REVIEWER_EMAILS`, the earlier
 * variable, is no longer read.
 *
 * The reviewer is always the authenticated admin user. Nothing here, and
 * nothing in the route that calls it, reads a name, an id or an email from
 * the request body (`admin/wholesale-application/[id]/approve` takes
 * `reviewed_by` from its body; that is the pattern not to copy). The user id
 * and the email the user module returns are both recorded on the sign-off.
 */
export const REVIEWER_ALLOWLIST_ENV = "JURISDICTION_RULE_REVIEWER_USER_IDS"

/** The variable the allowlist used to be read from. Named in the refusal so a stale deployment says why it refuses. */
export const RETIRED_REVIEWER_EMAILS_ENV = "JURISDICTION_RULE_REVIEWER_EMAILS"

/** The configured reviewer user ids. Entries are separated by commas, semicolons or whitespace. */
export function reviewerAllowlist(raw: string | undefined = process.env[REVIEWER_ALLOWLIST_ENV]): string[] {
  if (typeof raw !== "string") return []
  return raw
    .split(/[\s,;]+/)
    .map((entry) => entry.trim())
    .filter((entry) => entry.length > 0)
}

/** Whether this exact admin user id is on the list. An empty list admits no one. */
export function onReviewerAllowlist(userId: unknown, raw: string | undefined = process.env[REVIEWER_ALLOWLIST_ENV]): boolean {
  if (typeof userId !== "string" || userId.length === 0) return false
  return reviewerAllowlist(raw).includes(userId)
}

export type Reviewer = { user_id: string; name: string | null; email: string }

export type ReviewerResolution =
  | { ok: true; reviewer: Reviewer }
  | { ok: false; status: 401 | 403; type: "unauthorized" | "not_a_reviewer"; message: string }

type AuthContext = { actor_id?: unknown; actor_type?: unknown }
type AdminUser = { id: string; email?: string | null; first_name?: string | null; last_name?: string | null }
type UserModule = { retrieveUser(id: string): Promise<AdminUser> }

/** The admin user behind this request, or null for anything else (an API key, a seller, nobody). */
export function adminUserIdOf(req: MedusaRequest): string | null {
  const context = (req as MedusaRequest & { auth_context?: AuthContext }).auth_context
  if (!context || context.actor_type !== "user") return null
  return typeof context.actor_id === "string" && context.actor_id.length > 0 ? context.actor_id : null
}

/**
 * The reviewer for this request: the authenticated admin user, if and only if
 * their user id is on the allowlist and the user module still has that user
 * (a deleted user is not retrieved).
 */
export async function resolveReviewer(req: MedusaRequest): Promise<ReviewerResolution> {
  const userId = adminUserIdOf(req)
  if (!userId) {
    return {
      ok: false,
      status: 403,
      type: "not_a_reviewer",
      message: "A rule is signed off from an admin user's own login. An API key cannot review.",
    }
  }

  if (reviewerAllowlist().length === 0) {
    const retired = reviewerAllowlist(process.env[RETIRED_REVIEWER_EMAILS_ENV]).length > 0
    return {
      ok: false,
      status: 403,
      type: "not_a_reviewer",
      message:
        `No reviewer is configured, so nobody can review: ${REVIEWER_ALLOWLIST_ENV} is not set on this deployment.` +
        (retired ? ` ${RETIRED_REVIEWER_EMAILS_ENV} is set but is no longer read: list admin user ids instead.` : ""),
    }
  }

  if (!onReviewerAllowlist(userId)) {
    return {
      ok: false,
      status: 403,
      type: "not_a_reviewer",
      message: `Your admin login is not on the reviewer list (${REVIEWER_ALLOWLIST_ENV}, matched by admin user id).`,
    }
  }

  let user: AdminUser | null = null
  try {
    user = await req.scope.resolve<UserModule>(Modules.USER).retrieveUser(userId)
  } catch {
    user = null
  }
  const email = typeof user?.email === "string" && user.email.length > 0 ? user.email : null
  if (!user || user.id !== userId || !email) {
    return {
      ok: false,
      status: 403,
      type: "not_a_reviewer",
      message: "Your admin user could not be found, or has no email to record; a sign-off needs both.",
    }
  }

  const name = [user.first_name, user.last_name]
    .filter((part): part is string => typeof part === "string" && part.trim().length > 0)
    .map((part) => part.trim())
    .join(" ")

  return { ok: true, reviewer: { user_id: user.id, name: name.length > 0 ? name : null, email } }
}
