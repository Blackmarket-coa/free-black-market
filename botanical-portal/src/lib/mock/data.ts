const MAKER = "maker_self"

// Build a concrete pathway from a template id, applying per-maker fields.
function fromTemplate(
  templateId: string,
  id: string,
  overrides: Partial<ProductionPathway> = {}
): ProductionPathway {
  const t = PATHWAY_TEMPLATES.find((x) => x.id === templateId)!
  return {
    id,
    maker_id: MAKER,
    name: t.name,
    output_category: t.output_category,
    compliance_framework_id: t.compliance_framework_id,
    is_active: true,
    shelf_life_min_days: t.shelf_life_min_days,
    shelf_life_max_days: t.shelf_life_max_days,
    shelf_life_note: t.shelf_life_note,
    default_cure_time_days: t.default_cure_time_days,
    requires_ph_testing: t.requires_ph_testing,
    ph_threshold: t.ph_threshold,
    coa_required_for_wholesale: t.coa_required_for_wholesale ?? false,
    counts_toward_cottage_food_limit: t.counts_toward_cottage_food_limit,
    batch_number_prefix: t.batch_number_prefix,
    production_status_labels: t.production_status_labels,
    material_category_labels: t.material_category_labels,
    yield_unit_options: t.yield_unit_options,
    created_at: "2026-01-15T00:00:00Z",
    updated_at: "2026-06-01T00:00:00Z",
    ...overrides,
  }
}

